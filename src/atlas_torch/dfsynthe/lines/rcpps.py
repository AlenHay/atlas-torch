"""The x86 `rcpps` approximate reciprocal of the CPU that produced the stock reference, and the division sequence
ifx -fp-model fast compiles vectorised REAL*4 divisions into (dfsynthe.exe MAIN label 205 XNFDOP=XNFPEL/DOPPLE,
label 322 PROFILE=X/NSTEP**2, ...):

    r = rcpps(b);  q0 = a*r;  q = (a - q0*b)*r + q0          (one Newton step, separate mulps/subps/addps)

`rcpps` is implementation specific (AMD and Intel tables differ).  On the reference machine (lscpu: "AMD Custom
CPU 1772") the result for a normal input depends only on the top 12 mantissa bits, the exponent just scales it
(checked on 2**23 mantissas and 2e7 random floats): data/rcpps_amd_custom_apu_1772.npy holds the 4096 results
for inputs in [1, 2) (generated by data/rcpps_table.c with gcc -msse2).  Another table can be given with
$ATLAS_TORCH_RCPPS_TABLE (.npy uint32[4096], or the raw 2**23-entry dump of rcpps_table.c).
"""
from __future__ import annotations

import os
from functools import lru_cache
from pathlib import Path

import numpy as np
import torch

DEFAULT = Path(__file__).resolve().parent.parent / "data" / "rcpps_amd_custom_apu_1772.npy"


@lru_cache(maxsize=None)
def _table_np() -> np.ndarray:
    p = Path(os.environ.get("ATLAS_TORCH_RCPPS_TABLE", DEFAULT))
    t = np.load(p) if p.suffix == ".npy" else np.fromfile(p, dtype=np.uint32)
    if t.size == 1 << 23:
        blk = t.reshape(4096, -1)
        if not (blk == blk[:, :1]).all():
            raise ValueError("rcpps table depends on more than 12 mantissa bits")
        t = blk[:, 0].copy()
    if t.size != 4096:
        raise ValueError(f"unexpected rcpps table size {t.size}")
    return t.astype(np.int64)


_DEV: dict = {}


def _table(dev) -> torch.Tensor:
    if dev not in _DEV:
        _DEV[dev] = torch.from_numpy(_table_np()).to(dev)
    return _DEV[dev]


def rcpps(b: torch.Tensor) -> torch.Tensor:
    """rcpps of normal float32 values (sign kept, exponent rescaled; results outside the normal range -> 0/inf)."""
    bits = b.contiguous().view(torch.int32).to(torch.int64)
    m12 = (bits >> 11) & 0xFFF
    e = (bits >> 23) & 0xFF
    tb = _table(b.device)[m12]
    te = ((tb >> 23) & 0xFF) - (e - 127)
    out = (tb & 0x007FFFFF) | (te.clamp(0, 255) << 23) | (bits & 0x80000000)
    out = torch.where(te <= 0, bits & 0x80000000, out)                        # underflow -> +-0
    out = torch.where(te >= 255, (bits & 0x80000000) | 0x7F800000, out)       # overflow -> +-inf
    out = torch.where(e == 0, (bits & 0x80000000) | 0x7F800000, out)          # 0 (or DAZ subnormal) -> +-inf
    return out.to(torch.int32).view(torch.float32)


def div_nr(a: torch.Tensor, b: torch.Tensor) -> torch.Tensor:
    """a/b as compiled by ifx -fp-model fast in vector loops: rcpps + one Newton-Raphson step."""
    r = rcpps(b)
    q0 = a * r
    return (a - q0 * b) * r + q0
